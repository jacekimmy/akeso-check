/* What is actually broken, in the founder's words, each tied to the evidence
   that justifies it. A repair with no evidence behind it never appears. */
export function planRepairs({ detection, lifecycle = null, sandbox = null }) {
  const handler = detection.webhookHandlers?.[0] || null;
  const repairs = [];

  if (!handler) {
    repairs.push({
      id: "no-handler",
      title: "Your app has nowhere for Stripe to deliver payment events",
      because: "No Stripe webhook handler was found anywhere in the project.",
      severity: "critical",
    });
  } else {
    if (!handler.verifiesSignature) {
      repairs.push({
        id: "verify-signature",
        title: "Check Stripe's signature before trusting an event",
        because: `${handler.file} accepts events without verifying Stripe's signature, so anyone who finds the URL can forge them.`,
        severity: "critical",
      });
    } else if (!handler.rawBodySeen) {
      repairs.push({
        id: "raw-body",
        title: "Verify the signature against the raw request body",
        because: `${handler.file} verifies a signature, but the raw body was not seen. Verification against a re-serialized body fails at runtime.`,
        severity: "high",
      });
    }
    if (handler.missingEvents?.length) {
      repairs.push({
        id: "handle-all-events",
        title: "Handle every event that changes who is paying",
        because: `${handler.file} ignores ${handler.missingEvents.length} of the 7 lifecycle events: ${handler.missingEvents.join(", ")}.`,
        severity: handler.missingEvents.some((event) => event.includes("deleted") || event.includes("updated")) ? "critical" : "high",
      });
    }
  }

  /* Executed evidence outranks read evidence: a scenario that actually failed
     names its own repair, whichever driver saw it. */
  const failed = [
    ...(lifecycle?.results || []).filter((result) => result.outcome === "fail"),
    ...(sandbox?.phases || []).filter((phase) => phase.outcome === "fail").map((phase) => ({ id: phase.phase, name: phase.phase, expected: phase.expected })),
  ];
  const failedRemoval = failed.filter((result) => result.expected === false);
  const failedGrant = failed.filter((result) => result.expected === true);

  if (failedRemoval.length) {
    repairs.push({
      id: "removals-must-remove",
      title: "End paid access when the customer stops paying",
      because: `Tested against your running app: ${failedRemoval.map((r) => `"${r.name}"`).join(", ")} left access switched on. This is the failure that leaks money every day.`,
      severity: "critical",
    });
  }
  if (failedGrant.length) {
    repairs.push({
      id: "grants-must-grant",
      title: "Give paid access when the customer pays",
      because: `Tested against your running app: ${failedGrant.map((r) => `"${r.name}"`).join(", ")} left a paying customer locked out.`,
      severity: "critical",
    });
  }

  const idempotency = (lifecycle?.results || []).find((result) => result.id === "duplicate-delivery" && result.outcome === "fail");
  const ordering = (lifecycle?.results || []).find((result) => result.id === "out-of-order" && result.outcome === "fail");
  if (idempotency) {
    repairs.push({ id: "idempotency", title: "Apply the same event only once", because: "Stripe delivered the same event twice and your app changed state both times.", severity: "high" });
  }
  if (ordering) {
    repairs.push({ id: "ordering", title: "Ignore events that arrive late and out of order", because: "An older 'still active' event arrived after a cancellation and switched access back on.", severity: "high" });
  }

  const clientGate = (detection.accessDecisionSites || []).find((site) => site.clientSideOnly);
  if (clientGate) {
    repairs.push({
      id: "client-side-gate",
      title: "Decide paid access on the server, not in the browser",
      because: `${clientGate.file} decides paid access in browser code, which anyone can step around with devtools. The generated entitlement function belongs on the server; this one has to be moved by hand.`,
      severity: "high",
      handWork: true,
    });
  }

  return repairs;
}

