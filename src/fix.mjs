/* The backstop. Webhooks get missed: endpoints go down, deploys drop events,
   Stripe gives up after three days of retries. This re-derives the truth from
   Stripe itself, which is the only source that cannot drift. */
function reconcileJob(detection) {
  const typed = ts(detection);
  const isModule = detection.framework?.framework?.startsWith("next") || detection.framework?.framework === "node-other";
  const imports = isModule
    ? `import Stripe from "stripe";
import { allAccountEntitlements, applyBillingEntitlement, entitledByStatus, getBillingEntitlement } from "./entitlement";`
    : `const Stripe = require("stripe");
const { allAccountEntitlements, applyBillingEntitlement, entitledByStatus, getBillingEntitlement } = require("./entitlement");`;

  return `// ${AKESO_MARKER}
// Akeso: reconciliation backstop. Run it on a schedule (nightly is fine).
//
// Webhooks get missed. Endpoints go down mid-deploy, Stripe stops retrying
// after three days, and events can arrive out of order. This job does not
// trust events at all: it asks Stripe what is true now, compares that to what
// your app believes, and reports every disagreement.
//
// It is READ-ONLY by default. Pass { apply: true } to also correct
// disagreements, and even then it only ever grants access instantly; removals
// are listed for you to approve, because a wrong removal locks out a paying
// customer.
${imports}

const stripe = new Stripe(process.env.STRIPE_SECRET_KEY${typed ? "!" : ""});

export async function reconcile({ apply = false, removeToo = false } = {}) {
  const stripeSide = new Map();
  for await (const sub of stripe.subscriptions.list({ status: "all", limit: 100, expand: ["data.items.data.price"] })) {
    const account = sub.metadata?.account || sub.metadata?.account_id || sub.customer;
    const entitled = entitledByStatus(sub.status);
    // One account can have several subscriptions; any paying one entitles it.
    stripeSide.set(String(account), (stripeSide.get(String(account)) || false) || entitled);
  }

  const appSide = await allAccountEntitlements();
  const shouldGrant = [];
  const shouldRemove = [];

  for (const row of appSide) {
    const stripeSays = stripeSide.get(String(row.account));
    if (stripeSays === undefined) continue; // no subscription at all: reported, never assumed
    if (stripeSays && !row.billingEntitled) shouldGrant.push(row.account);
    if (!stripeSays && row.billingEntitled) shouldRemove.push(row.account);
  }

  const applied = [];
  if (apply) {
    for (const account of shouldGrant) {
      applied.push({ account, direction: "grant", ...await applyBillingEntitlement(account, true, { expected: false, reasonCode: "reconcile:grant", idempotencyKey: \`reconcile-grant-\${account}-\${new Date().toISOString().slice(0, 10)}\` }) });
    }
    if (removeToo) {
      for (const account of shouldRemove) {
        applied.push({ account, direction: "remove", ...await applyBillingEntitlement(account, false, { expected: true, reasonCode: "reconcile:remove", idempotencyKey: \`reconcile-remove-\${account}-\${new Date().toISOString().slice(0, 10)}\` }) });
      }
    }
  }

  return {
    checked: appSide.length,
    shouldGrant,
    shouldRemove,
    applied,
    clean: shouldGrant.length === 0 && shouldRemove.length === 0,
    at: new Date().toISOString(),
  };
}
`;
}

/* The two endpoints Akeso talks to, generated into the customer's own app.
 *
 * This is the whole surface of what Akeso can do to an app, which is why it is
 * generated code the founder reads and commits rather than a database
 * connection they hand over. Deleting these two files removes Akeso's access
 * completely, and that has to stay true.
 *
 * Both refuse everything that is not signed with a shared secret the founder
 * generates, and the restore endpoint additionally goes through the app's own
 * guarded entitlement function, so blocks and human overrides still win.
 */
function akesoEndpoints(detection, importFrom) {
  const typed = ts(detection);
  const t = (annotation) => (typed ? annotation : "");
  const framework = detection.framework?.framework || "node-other";
  const nextish = framework.startsWith("next");
  /* Each generated file computes its OWN specifier for the modules it imports.
     Reusing the webhook handler's specifier worked only by accident when the
     two files happened to sit at the same depth, and produced an import of a
     name the target module does not export as soon as they did not. */
  const routeDir = nextish ? "app/api/akeso" : "akeso";
  const routePath = (name) => (nextish
    ? path.join(routeDir, name, "route.x")
    : path.join(routeDir, `${name}.x`));
  const entitlementFrom = (name) => importFrom(routePath(name), "entitlement");
  const verifyFrom = (name) => importFrom(routePath(name), "verify");

  const verifier = `// ${AKESO_MARKER}
// Akeso: shared-secret verification for the two Akeso endpoints.
//
// Same signing scheme Stripe uses, for the same reason: a timestamp inside the
// signed material, so a captured request cannot be replayed later.
import { createHmac, timingSafeEqual } from "node:crypto";

const SECRET = process.env.AKESO_SHARED_SECRET;
const TOLERANCE_SECONDS = 300;

export function verifyAkesoRequest(rawBody${t(": string")}, header${t(": string | null")}) {
  if (!SECRET) return { valid: false, reason: "AKESO_SHARED_SECRET is not set in this app" };
  if (!header) return { valid: false, reason: "no signature" };

  const parts = Object.fromEntries(String(header).split(",").map((part) => part.split("=")));
  if (!parts.t || !parts.v1) return { valid: false, reason: "malformed signature" };

  const age = Math.abs(Math.floor(Date.now() / 1000) - Number(parts.t));
  if (!Number.isFinite(age) || age > TOLERANCE_SECONDS) return { valid: false, reason: "signature too old" };

  const expected = createHmac("sha256", SECRET).update(\`\${parts.t}.\${rawBody}\`).digest("hex");
  try {
    if (!timingSafeEqual(Buffer.from(expected, "hex"), Buffer.from(parts.v1, "hex"))) {
      return { valid: false, reason: "signature does not match" };
    }
  } catch { return { valid: false, reason: "signature does not match" }; }

  return { valid: true };
}
`;

  /* The write endpoint. Everything dangerous about Akeso passes through here,
     so it is deliberately small enough to read in one sitting. */
  const restore = `// ${AKESO_MARKER}
// Akeso: the ONLY way Akeso can change anything in this app.
//
// Read this file. It is the complete list of what Akeso is able to do:
// set one boolean, on one account, through your own guarded function, and only
// when the row still looks the way Akeso last read it.
//
// Delete this file and Akeso can no longer write to your app at all.
import { applyBillingEntitlement, AKESO_RULE_VERSION } from "${entitlementFrom("restore")}";
import { verifyAkesoRequest } from "${verifyFrom("restore")}";

export async function POST(request${t(": Request")}) {
  const rawBody = await request.text();
  const check = verifyAkesoRequest(rawBody, request.headers.get("akeso-signature"));
  if (!check.valid) return new Response(check.reason, { status: 401 });

  let body${t(": any")};
  try { body = JSON.parse(rawBody); } catch { return new Response("bad json", { status: 400 }); }

  const { account, target, expectedState, reasonCode, idempotencyKey, ruleVersion, dryRun } = body;
  if (typeof account !== "string" || typeof target !== "boolean") {
    return new Response("account and target are required", { status: 400 });
  }

  // The rule version is part of the contract: if your billing policy changed
  // since Akeso prepared this restore, the restore is stale and must not run.
  if (ruleVersion && ruleVersion !== AKESO_RULE_VERSION) {
    return Response.json({ result: "conflict", reason: "your billing rules changed since this was prepared" });
  }

  // A dry run reports what would happen and changes nothing. Akeso treats an
  // "applied" answer to a dry run as a protocol violation, so never do work here.
  if (dryRun) {
    return Response.json({ result: "dry_run", wouldTarget: target, account });
  }

  try {
    const outcome = await applyBillingEntitlement(account, target, {
      expected: typeof expectedState === "boolean" ? expectedState : null,
      reasonCode: reasonCode || "akeso:restore",
      idempotencyKey: idempotencyKey || \`akeso-\${account}-\${Date.now()}\`,
    });
    return Response.json({
      ...outcome,
      // Akeso does not take this endpoint's word for success either: it re-reads.
      // Reporting verified truthfully is what makes that check meaningful.
      verified: Boolean(outcome.verified),
      after: outcome.after ? { billingEntitled: outcome.after.billingEntitled } : null,
      before: outcome.before ? { billingEntitled: outcome.before.billingEntitled } : null,
    });
  } catch (error${t(": any")}) {
    return Response.json({ result: "failed", reason: error.message }, { status: 500 });
  }
}
`;

  /* The read endpoint. Monitor needs the app's own answer for every account;
     without it the comparison has only one side. */
  const entitlements = `// ${AKESO_MARKER}
// Akeso: the read side. Returns this app's own answer to "who currently has
// paid access", so it can be compared against Stripe.
//
// Signed like the restore endpoint, because an unauthenticated list of who is
// paying you is a data leak, not a convenience.
import { allAccountEntitlements } from "${entitlementFrom("entitlements")}";
import { verifyAkesoRequest } from "${verifyFrom("entitlements")}";

export async function POST(request${t(": Request")}) {
  const rawBody = await request.text();
  const check = verifyAkesoRequest(rawBody, request.headers.get("akeso-signature"));
  if (!check.valid) return new Response(check.reason, { status: 401 });

  try {
    const accounts = await allAccountEntitlements();
    return Response.json({ accounts, readAt: new Date().toISOString() });
  } catch (error${t(": any")}) {
    // A failed read is reported as a failure, never as an empty list. An empty
    // list would read as "nobody has access" and could trigger mass grants.
    return Response.json({ error: error.message }, { status: 500 });
  }
}
`;

  return { verifier, restore, entitlements, nextish };
}

function migrationSql(detection) {
  const column = detection.database?.entitlementColumn || "billing_entitled";
  const table = detection.database?.entitlementTable || "profiles";
  return `-- ${AKESO_MARKER} — paste this into your database's SQL editor.
-- Akeso never runs schema changes for you. Read it first; it only adds.

-- Every Stripe event id we have already applied, so a repeat delivery is a
-- no-op instead of a second state change.
create table if not exists akeso_processed_events (
  event_id   text primary key,
  event_type text not null,
  applied_at timestamptz not null default now()
);

-- The newest event already applied per account, so a late event that Stripe
-- delivers out of order cannot overwrite a newer decision.
create table if not exists akeso_event_watermarks (
  account_id         text primary key,
  last_event_created bigint not null,
  updated_at         timestamptz not null default now()
);

-- Optional but recommended: the fields that keep a billing fix from becoming
-- an incident. Without them, a restore cannot tell a banned account from an
-- unpaid one. Akeso refuses to write to an account carrying either block.
alter table ${table} add column if not exists complimentary_access boolean not null default false;
alter table ${table} add column if not exists billing_override     boolean not null default false;
alter table ${table} add column if not exists admin_block          boolean not null default false;
alter table ${table} add column if not exists abuse_block          boolean not null default false;

-- The entitlement column itself, if the Check did not find one.
alter table ${table} add column if not exists ${column} boolean not null default false;
`;
}

/* Every file the repair would write, with its reason. Pure: builds the plan
   without touching the disk, so the dry run and the apply cannot disagree. */
export function buildFixPlan({ detection, lifecycle = null, sandbox = null, withEndpoints = false }) {
  const repairs = planRepairs({ detection, lifecycle, sandbox });
  const framework = detection.framework?.framework || "node-other";
  const dir = "akeso";

  /* Match the project's own file shape. An existing handler is replaced in
     place with its own extension, so the app's router keeps finding it. */
  const existingHandler = detection.webhookHandlers?.[0]?.file || null;
  const handlerExtension = existingHandler?.match(/\.(ts|tsx|js|mjs|jsx)$/)?.[1]
    || (ts(detection) ? "ts" : "mjs");
  const moduleExtension = ts(detection) ? "ts" : (framework === "express" ? "js" : "mjs");

  const handlerTarget = existingHandler
    || (framework === "next-app-router" ? `app/api/stripe/webhook/route.${handlerExtension}`
      : framework === "next-pages" ? `pages/api/stripe/webhook.${handlerExtension}`
      : `akeso/webhook.${moduleExtension}`);

  const entitlementPath = path.join(dir, `entitlement.${moduleExtension}`);

  /* How one generated file imports another.
     "@/akeso/entitlement" only resolves in a project that configured that
     alias; everywhere else it must be a relative path computed from the
     IMPORTING file's own directory. Deriving one specifier and reusing it
     everywhere worked only while two files happened to sit at the same depth. */
  const alias = detection.framework?.pathAlias;
  const importFrom = (fromFile, moduleName) => {
    if (alias) return `${alias}akeso/${moduleName}`;
    const target = path.join(dir, `${moduleName}.${moduleExtension}`);
    const relative = path.relative(path.dirname(fromFile), target).replace(/\\/g, "/");
    const specifier = relative.startsWith(".") ? relative : `./${relative}`;
    /* Node's ESM resolver needs the real extension; TypeScript wants it gone. */
    return ts(detection) ? specifier.replace(/\.ts$/, "") : specifier;
  };
  const entitlementImport = importFrom(handlerTarget, "entitlement");

  const files = [
    { path: entitlementPath, contents: entitlementModule(detection), why: "the one place that touches your database" },
    { path: handlerTarget, contents: webhookHandler(detection, entitlementImport), why: "the corrected Stripe webhook handler", replaces: Boolean(existingHandler) },
    { path: path.join(dir, `reconcile.${moduleExtension}`), contents: reconcileJob(detection), why: "the nightly backstop for events that never arrived" },
    { path: path.join(dir, "migration.sql"), contents: migrationSql(detection), why: "the tables the repair needs (you paste this yourself)", manual: true },
  ];

  /* The monitoring endpoints are opt-in, because they are the only way Akeso
     can ever read or write this app and a founder who only wanted the repair
     should not silently get a write path too. */
  if (withEndpoints) {
    const endpoints = akesoEndpoints(detection, importFrom);
    const routeDir = endpoints.nextish ? "app/api/akeso" : "akeso";
    const routeFile = (name) => (endpoints.nextish
      ? path.join(routeDir, name, `route.${handlerExtension}`)
      : path.join(routeDir, `${name}.${moduleExtension}`));

    files.push(
      { path: path.join(dir, `verify.${moduleExtension}`), contents: endpoints.verifier, why: "checks that a request really came from your own Akeso run" },
      { path: routeFile("restore"), contents: endpoints.restore, why: "the ONLY way Akeso can change anything here (delete it and it cannot)" },
      { path: routeFile("entitlements"), contents: endpoints.entitlements, why: "lets the monitor read your app's own answer for every account" },
    );
  }

  return { repairs, files, framework, entitlementImport, withEndpoints };
}

/* -------------------------------------------------------------- applying */

const sha = (text) => createHash("sha256").update(text).digest("hex").slice(0, 16);

export async function gitState(root) {
  const { execFile } = await import("node:child_process");
  const run = (args) => new Promise((resolve) => {
    execFile("git", ["-C", root, ...args], { timeout: 5000 }, (error, stdout) => resolve(error ? null : stdout.trim()));
  });
  if ((await run(["rev-parse", "--is-inside-work-tree"])) !== "true") return { repo: false, clean: null, dirtyFiles: [] };
  const status = await run(["status", "--porcelain"]);
  const dirtyFiles = (status || "").split("\n").filter(Boolean).map((line) => line.slice(3));
  return { repo: true, clean: dirtyFiles.length === 0, dirtyFiles };
}

/* Writes the plan, all of it or none of it.
 *
 * Everything is read and backed up BEFORE the first byte is written, so a
 * failure halfway through cannot leave an app with a new webhook handler and
 * no entitlement module — which is a worse app than the broken one it
 * replaced. If any write fails, everything already written is rolled back
 * from the copies held in memory. */
export async function applyFixPlan(root, plan, { stamp = new Date().toISOString().replace(/[:.]/g, "-") } = {}) {
  const backupDir = path.join(BACKUP_ROOT, stamp);

  /* Phase 1: read every current file and write every backup. Nothing in the
     app has changed yet. */
  const staged = [];
  for (const file of plan.files) {
    const target = path.join(root, file.path);
    const existing = await readFile(target, "utf8").catch(() => null);
    if (existing !== null && !file.manual) {
      const backupTarget = path.join(root, backupDir, file.path);
      await mkdir(path.dirname(backupTarget), { recursive: true });
      await copyFile(target, backupTarget);
    }
    staged.push({ file, target, existing });
  }

  /* Phase 2: write. On any failure, put back everything already written. */
  const written = [];
  try {
    for (const { file, target, existing } of staged) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, file.contents);
      written.push({
        path: file.path,
        /* What happened to the file, always — a separate "written" category
           for manual files left revert unable to undo them, and reporting the
           reason as "no backup exists" when the truth was "this file is new". */
        action: existing === null ? "created" : "replaced",
        ...(file.manual ? { manual: true } : {}),
        before: existing === null ? null : sha(existing),
        after: sha(file.contents),
      });
    }
  } catch (error) {
    for (const done of written) {
      const stagedFile = staged.find((row) => row.file.path === done.path);
      if (stagedFile.existing === null) await rm(stagedFile.target, { force: true });
      else await writeFile(stagedFile.target, stagedFile.existing);
    }
    throw new Error(`the repair was rolled back: ${error.message}`);
  }

  return { backupDir, written };
}

/* Puts the repair on its own git branch, so the founder's current branch is
   never the thing being experimented on. Best-effort: a project without git
   still gets the backup-and-revert path, which is why this never throws. */
export async function branchForFix(root, name) {
  const { execFile } = await import("node:child_process");
  const run = (args) => new Promise((resolve) => {
    execFile("git", ["-C", root, ...args], { timeout: 5000 }, (error, stdout) => resolve(error ? null : stdout.trim()));
  });
  if ((await run(["rev-parse", "--is-inside-work-tree"])) !== "true") return { branched: false, reason: "not a git repository" };
  const from = await run(["rev-parse", "--abbrev-ref", "HEAD"]);
  const created = await run(["checkout", "-b", name]);
  if (created === null) return { branched: false, reason: `could not create branch ${name}`, from };
  return { branched: true, branch: name, from };
}

/* Puts it back. Refuses any file that no longer carries the marker: that means
   a human edited it after the fix, and their work outranks the revert. */
export async function revertFix(root, fixRecord) {
  const restored = [];
  const refused = [];

  for (const file of fixRecord.files || []) {
    const target = path.join(root, file.path);
    const current = await readFile(target, "utf8").catch(() => null);
    if (current !== null && !current.includes(AKESO_MARKER)) {
      refused.push({ path: file.path, reason: "the file was edited after the fix, so it was left alone" });
      continue;
    }
    const backup = path.join(root, fixRecord.backupDir, file.path);
    const saved = await readFile(backup, "utf8").catch(() => null);
    if (saved === null) {
      if (file.action === "created" && current !== null) {
        await rm(target, { force: true });
        restored.push({ path: file.path, action: "removed" });
      } else {
        refused.push({ path: file.path, reason: "no backup exists for this file" });
      }
      continue;
    }
    await writeFile(target, saved);
    restored.push({ path: file.path, action: "restored" });
  }

  return { restored, refused };
}
