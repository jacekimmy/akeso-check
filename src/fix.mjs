/* The seven events, and what each one means for entitlement. This table is the
   heart of the repair and is identical for every app, which is exactly why it
   belongs in generated code and not in a founder's head. */
const EVENT_LOGIC = `  switch (event.type) {
    case "checkout.session.completed":
      // A completed checkout means paid, unless the session says otherwise.
      target = object.payment_status ? object.payment_status === "paid" : true;
      break;
    case "invoice.paid":
      target = true;
      break;
    case "invoice.payment_failed":
      // Not a removal on its own. Stripe retries; the subscription status
      // events below carry the real decision.
      target = null;
      break;
    case "customer.subscription.created":
    case "customer.subscription.updated":
      target = entitledByStatus(object.status);
      break;
    case "customer.subscription.deleted":
      target = false;
      break;
    case "charge.refunded":
      // Your policy. Default: a refund ends access. Change this one line if
      // your policy differs, and bump AKESO_RULE_VERSION.
      target = false;
      break;
    default:
      target = null;
  }`;

