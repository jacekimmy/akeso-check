/* The Fix: turns what the Check found into working code, applies it only when
 * the founder says so, and can always put it back.
 *
 * Shape of the repair, and why it is this shape:
 *
 *   akeso/entitlement.*   ONE file holds every line that touches this app's
 *                         database. Everything else generated here is app-
 *                         agnostic and correct as written, so there is exactly
 *                         one place a founder (or their agent) can get wrong.
 *   the webhook handler   raw-body signature check, all seven events,
 *                         idempotent by event id, ordered by event created,
 *                         entitlement derived from subscription status.
 *   akeso/reconcile.*     the backstop: re-derives entitlement from Stripe
 *                         itself, because webhooks are missable by design.
 *   akeso/migration.sql   the idempotency and ordering tables. DDL is never
 *                         run by us; the founder pastes it.
 *
 * Safety, in the order it matters. Nothing here is applied without --apply.
 * Nothing is overwritten without a backup. A dirty git tree stops the run,
 * because "I can just undo it" has to be true. Every generated file carries a
 * marker, and revert refuses to touch a file that lost its marker (that means
 * a human edited it, and their work outranks ours).
 */

